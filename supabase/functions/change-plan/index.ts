// supabase/functions/change-plan/index.ts
//
// UPGRADES the calling user's ACTIVE subscription to a higher plan.
//
//   * The customer pays ONLY the difference between the new plan price and the
//     price they currently pay (e.g. BASIC 24,99 -> PRO 49,99 = 25,00 today).
//   * Today becomes the new renewal day: the billing cycle is reset to "now", so from
//     now on they are charged the FULL new price on this same day every month.
//   * If the payment fails, NOTHING changes (the subscription stays as it was).
//
// How it works in Stripe (one atomic update):
//   1. A pending negative invoice item credits the current price.
//   2. subscriptions.update swaps the price (inline price_data, same pattern as
//      create-checkout-session), resets billing_cycle_anchor to "now", with no
//      proration, and payment_behavior "error_if_incomplete".
//   3. The invoice generated by that update = new price - credit = the difference.
//
// Body:  { planId: "mid" | "high", preview?: boolean }
//   preview: true  -> only returns the numbers, changes nothing.
//
// Deploy WITH JWT verification (the default). Do NOT add this to the webhook config.
import Stripe from "npm:stripe@^18";
import { createClient } from "npm:@supabase/supabase-js@^2";
import { syncSubscription } from "../_shared/billing.ts";

const CORS_HEADERS: Record<string, string> = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
};

function json(body: unknown, status = 200): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { ...CORS_HEADERS, "Content-Type": "application/json" },
  });
}

type PlanId = "low" | "mid" | "high";

const RANK: Record<PlanId, number> = { low: 1, mid: 2, high: 3 };

function isPlanId(value: unknown): value is PlanId {
  return value === "low" || value === "mid" || value === "high";
}

/** Stripe refuses charges below roughly 0,50 EUR. */
const MIN_CHARGE_CENTS = 50;

/** Same day next month, clamped to the last day of that month (UTC). */
function addOneMonth(from: Date): Date {
  const y = from.getUTCFullYear();
  const m = from.getUTCMonth();
  const d = from.getUTCDate();
  const lastDayNextMonth = new Date(Date.UTC(y, m + 2, 0)).getUTCDate();
  return new Date(
    Date.UTC(
      y,
      m + 1,
      Math.min(d, lastDayNextMonth),
      from.getUTCHours(),
      from.getUTCMinutes(),
      from.getUTCSeconds(),
    ),
  );
}

Deno.serve(async (req: Request): Promise<Response> => {
  if (req.method === "OPTIONS") return new Response("ok", { headers: CORS_HEADERS });
  if (req.method !== "POST") return json({ error: "Method not allowed" }, 405);

  const stripeKey = Deno.env.get("STRIPE_SECRET_KEY");
  const supabaseUrl = Deno.env.get("SUPABASE_URL");
  const anonKey = Deno.env.get("SUPABASE_ANON_KEY");
  const serviceKey = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY");

  if (!stripeKey || !supabaseUrl || !anonKey || !serviceKey) {
    console.error("Missing environment configuration");
    return json({ error: "Server misconfigured" }, 500);
  }

  // ---- 1. validate input + caller ---------------------------------------
  let body: { planId?: unknown; preview?: unknown };
  try {
    body = JSON.parse(await req.text());
  } catch {
    return json({ error: "Invalid JSON body" }, 400);
  }
  if (!isPlanId(body.planId)) return json({ error: "Unknown plan" }, 400);
  const targetPlanId: PlanId = body.planId;
  const previewOnly = body.preview === true;

  const authHeader = req.headers.get("Authorization") ?? "";
  if (!authHeader.startsWith("Bearer ")) return json({ error: "Unauthorized" }, 401);

  const userClient = createClient(supabaseUrl, anonKey, {
    global: { headers: { Authorization: authHeader } },
    auth: { persistSession: false },
  });
  const { data: userData, error: userError } = await userClient.auth.getUser();
  const user = userData?.user;
  if (userError || !user) return json({ error: "Unauthorized" }, 401);

  const admin = createClient(supabaseUrl, serviceKey, { auth: { persistSession: false } });
  const stripe = new Stripe(stripeKey);

  let creditItemId: string | null = null;

  try {
    // ---- 2. the user's current ACTIVE subscription -------------------------
    const { data: subRow, error: subError } = await admin
      .from("subscriptions")
      .select("stripe_subscription_id, plan_id, status")
      .eq("user_id", user.id)
      .eq("status", "active")
      .order("created_at", { ascending: false })
      .limit(1)
      .maybeSingle();

    if (subError) {
      console.error("subscription lookup failed", subError.message);
      return json({ error: "Δεν φορτώθηκε η συνδρομή σου." }, 500);
    }
    if (!subRow || !subRow.stripe_subscription_id) {
      return json({ error: "Δεν βρέθηκε ενεργή συνδρομή για αναβάθμιση." }, 404);
    }

    const currentPlanId = subRow.plan_id;
    if (!isPlanId(currentPlanId)) {
      console.error("Unknown current plan_id", currentPlanId);
      return json({ error: "Άγνωστο τρέχον πλάνο." }, 500);
    }
    if (RANK[targetPlanId] <= RANK[currentPlanId]) {
      return json({ error: "Μπορείς να αναβαθμίσεις μόνο σε ανώτερο πλάνο." }, 400);
    }

    // ---- 3. plans (current name + target price) from the database ----------
    const { data: planRows, error: plansError } = await admin
      .from("plans")
      .select("id, name, price_cents, currency, active, stripe_product_id")
      .in("id", [currentPlanId, targetPlanId]);
    if (plansError) {
      console.error("plans lookup failed", plansError.message);
      return json({ error: "Could not load the plans." }, 500);
    }
    const currentPlan = planRows?.find((p) => p.id === currentPlanId);
    const targetPlan = planRows?.find((p) => p.id === targetPlanId);
    if (!targetPlan || !targetPlan.active) {
      return json({ error: "Το πλάνο δεν είναι διαθέσιμο." }, 404);
    }

    const newAmount = Number(targetPlan.price_cents);
    if (!Number.isInteger(newAmount) || newAmount < MIN_CHARGE_CENTS) {
      return json({ error: "Το πλάνο δεν έχει έγκυρη τιμή." }, 500);
    }
    const currency = String(targetPlan.currency ?? "eur").toLowerCase();

    // ---- 4. the live Stripe subscription ------------------------------------
    const sub = await stripe.subscriptions.retrieve(String(subRow.stripe_subscription_id), {
      expand: ["items.data.price"],
    });

    if (sub.status !== "active") {
      return json(
        { error: "Η συνδρομή σου δεν είναι ενεργή αυτή τη στιγμή. Ρύθμισε πρώτα την πληρωμή σου." },
        409,
      );
    }
    if (sub.items.data.length !== 1) {
      console.error("Unexpected subscription items", sub.id, sub.items.data.length);
      return json({ error: "Η συνδρομή έχει απροσδόκητη μορφή. Επικοινώνησε μαζί μας." }, 409);
    }
    const item = sub.items.data[0];
    if (!item) return json({ error: "Η συνδρομή δεν έχει προϊόν." }, 409);
    if ((item.quantity ?? 1) !== 1) {
      return json({ error: "Η συνδρομή έχει απροσδόκητη ποσότητα. Επικοινώνησε μαζί μας." }, 409);
    }

    // What the customer ACTUALLY pays today (may differ from today's list price).
    const currentAmount = item.price.unit_amount;
    if (typeof currentAmount !== "number") {
      return json({ error: "Δεν βρέθηκε η τρέχουσα τιμή της συνδρομής." }, 409);
    }
    if (String(item.price.currency).toLowerCase() !== currency) {
      return json({ error: "Διαφορετικό νόμισμα στα δύο πλάνα. Επικοινώνησε μαζί μας." }, 409);
    }

    const difference = newAmount - currentAmount;
    if (difference < MIN_CHARGE_CENTS) {
      return json(
        { error: "Δεν μπορεί να γίνει αναβάθμιση με αυτή την τιμή. Επικοινώνησε μαζί μας." },
        409,
      );
    }

    const nextRenewal = addOneMonth(new Date()).toISOString();

    // ---- 5. preview: numbers only, nothing is changed ----------------------
    if (previewOnly) {
      return json({
        currentPlanId,
        targetPlanId,
        currentPlanName: String(currentPlan?.name ?? currentPlanId),
        targetPlanName: String(targetPlan.name),
        currency,
        currentAmountCents: currentAmount,
        newAmountCents: newAmount,
        differenceCents: difference,
        nextRenewal,
      });
    }

    // ---- 6. the Stripe product of the target plan --------------------------
    let productId: string | null = (targetPlan.stripe_product_id as string | null) ?? null;
    if (productId) {
      try {
        await stripe.products.update(productId, { name: String(targetPlan.name) });
      } catch (err) {
        console.error("Stored product unusable, creating a new one", err);
        productId = null;
      }
    }
    if (!productId) {
      const product = await stripe.products.create({
        name: String(targetPlan.name),
        metadata: { plan_id: String(targetPlan.id) },
      });
      productId = product.id;
      const { error: saveError } = await admin
        .from("plans")
        .update({ stripe_product_id: productId })
        .eq("id", targetPlan.id);
      if (saveError) console.error("Could not store stripe_product_id", saveError.message);
    }

    const customerId = typeof sub.customer === "string" ? sub.customer : sub.customer.id;

    // ---- 7. credit the current price, then switch plan + reset the cycle ----
    const credit = await stripe.invoiceItems.create({
      customer: customerId,
      subscription: sub.id,
      amount: -currentAmount,
      currency,
      description: `Πίστωση τρέχοντος πλάνου (${String(currentPlan?.name ?? currentPlanId)})`,
    });
    creditItemId = credit.id;

    const updated = await stripe.subscriptions.update(sub.id, {
      items: [
        {
          id: item.id,
          price_data: {
            currency,
            product: productId,
            unit_amount: newAmount,
            recurring: { interval: "month" },
          },
        },
      ],
      billing_cycle_anchor: "now", // today = the new renewal day
      proration_behavior: "none", // we apply our own fixed credit above
      payment_behavior: "error_if_incomplete", // payment fails -> nothing changes
      cancel_at_period_end: false, // upgrading means staying
      metadata: { plan_id: targetPlanId, supabase_user_id: user.id },
      expand: ["latest_invoice"],
    });
    creditItemId = null; // consumed by the invoice, nothing to clean up

    // ---- 8. report what really happened + sync the database right away ------
    const invoice = updated.latest_invoice;
    const charged = invoice && typeof invoice !== "string" ? (invoice.amount_paid ?? null) : null;
    if (charged !== null && charged !== difference) {
      console.error(
        `change-plan ${user.id}: expected ${difference} but charged ${charged} (discount applied?)`,
      );
    }
    console.log(
      `change-plan ${user.id}: ${currentPlanId} -> ${targetPlanId}, charged ${charged ?? "?"} ${currency}`,
    );

    try {
      const fresh = await stripe.subscriptions.retrieve(sub.id, { expand: ["items.data.price"] });
      const result = await syncSubscription(admin, fresh, { planId: targetPlanId });
      if (!result) throw new Error("syncSubscription returned nothing");
    } catch (err) {
      // The webhook (customer.subscription.updated) will sync as well: this is a safety net.
      console.error("immediate sync failed, falling back to plan_id update", err);
      const { error: fallbackError } = await admin
        .from("subscriptions")
        .update({ plan_id: targetPlanId })
        .eq("stripe_subscription_id", sub.id);
      if (fallbackError) console.error("fallback plan_id update failed", fallbackError.message);
    }

    // current_period_end lives on the subscription (older API) or on its items (newer API).
    const periodEnd: number | undefined =
      (updated as unknown as { current_period_end?: number }).current_period_end ??
      updated.items.data[0]?.current_period_end;

    return json({
      ok: true,
      planId: targetPlanId,
      chargedCents: charged,
      nextRenewal: periodEnd ? new Date(periodEnd * 1000).toISOString() : nextRenewal,
    });
  } catch (error) {
    // The update failed: remove the pending credit so it can never leak into a later invoice.
    if (creditItemId) {
      try {
        await stripe.invoiceItems.del(creditItemId);
      } catch (cleanupErr) {
        console.error("could not remove pending credit item", creditItemId, cleanupErr);
      }
    }

    console.error("change-plan failed", error);
    const e = error as { type?: string; code?: string; message?: string };
    if (e?.type === "StripeCardError" || e?.code === "subscription_payment_intent_requires_action") {
      return json(
        {
          error:
            "Η πληρωμή δεν ολοκληρώθηκε και η συνδρομή σου δεν άλλαξε. Έλεγξε την κάρτα σου ή δοκίμασε άλλη.",
          detail: e.message,
        },
        402,
      );
    }
    const message = error instanceof Error ? error.message : String(error);
    return json({ error: `Η αναβάθμιση απέτυχε: ${message}` }, 500);
  }
});